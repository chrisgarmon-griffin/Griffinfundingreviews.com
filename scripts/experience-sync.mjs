/**
 * Experience.com sync. Pulls Griffin Funding's reviews from the review-widget feed
 * and keeps only aggregate figures: the company's own-review rating and count, the
 * blended figure the FAQ explains, and each loan officer's rating and count.
 *
 * Privacy: the feed returns borrower last names and email addresses. Nothing here
 * stores, logs, or returns a review's personal fields. `summarize` reads scores,
 * sources, and loan officer names only; `sanitizeReview` is the single allowlist
 * for anything quote-related and drops every field not named in it.
 *
 * Usage (needs EXPERIENCE_API_KEY and EXPERIENCE_WIDGET_KEY):
 *   node scripts/experience-sync.mjs            write src/data/experience.generated.ts
 *   node scripts/experience-sync.mjs --dry-run  print the figures, write nothing
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const FEED_URL = "https://api.experience.com/v3/core/account/review_widget";
const PAGE_SIZE = 1000;

/** Experience.com labels its own reviews "Experience"; copies are "Google", "Zillow", "Facebook". */
export function isOwnReview(review) {
  return review.survey_source_label === "Experience";
}

/** "Sarah Howell at Griffin Funding" or "Sam  Tebay" -> "sarah-howell" / "sam-tebay". */
export function officerId(agentName) {
  if (!agentName) return null;
  const name = String(agentName)
    .replace(/\s+at\s+Griffin Funding\s*$/i, "")
    .trim()
    .toLowerCase();
  const id = name
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return id || null;
}

function round2(n) {
  return Math.round(n * 100) / 100;
}

function average(scores) {
  return scores.reduce((sum, s) => sum + s, 0) / scores.length;
}

/**
 * Aggregate figures from the feed's summary block and its reviews.
 * Officer figures count every source, matching the officer's own Experience.com
 * profile; the company figure counts own reviews only, so the site never counts a
 * Google or Zillow review twice.
 */
export function summarize(summary, reviews, checked) {
  const own = reviews.filter(isOwnReview);
  const scores = new Map();
  for (const review of reviews) {
    const id = officerId(review.agent_name);
    if (!id) continue;
    const score = Number(review.score);
    if (!Number.isFinite(score) || score <= 0) continue;
    if (!scores.has(id)) scores.set(id, []);
    scores.get(id).push(score);
  }
  const officers = {};
  for (const id of [...scores.keys()].sort()) {
    const list = scores.get(id);
    officers[id] = { rating: round2(average(list)), count: list.length };
  }
  return {
    checked,
    company: {
      rating: Number(summary.experience_avg_score),
      count: Number(summary.experience_review_count),
    },
    blended: {
      rating: Number(summary.average_score),
      count: Number(summary.count),
    },
    ownReviewsInFeed: own.length,
    officers,
  };
}

/** Checks that the feed's own-review total agrees with the reviews it returned. */
export function validate(result) {
  const problems = [];
  const { company, blended } = result;
  if (!(company.rating > 0 && company.rating <= 5))
    problems.push(`company rating out of range: ${company.rating}`);
  if (!(company.count > 0)) problems.push(`company count not positive: ${company.count}`);
  if (!(blended.count >= company.count))
    problems.push(`blended count ${blended.count} below own count ${company.count}`);
  if (result.ownReviewsInFeed !== company.count)
    problems.push(
      `feed returned ${result.ownReviewsInFeed} own reviews but reports ${company.count}`,
    );
  return problems;
}

/**
 * The only fields a review candidate may carry. First name and last initial only,
 * never the email, full last name, photo, or transaction ids.
 */
export function sanitizeReview(review) {
  const first = String(review.customer_first_name ?? "").trim();
  const initial = String(review.customer_last_name ?? "").trim().charAt(0);
  return {
    id: review.id,
    author: first ? `${first}${initial ? ` ${initial.toUpperCase()}.` : ""}` : "Anonymous",
    city: review.city ?? null,
    state: review.state ?? null,
    date: review.survey_completed_on ?? null,
    score: Number(review.score),
    officer: officerId(review.agent_name),
    loanType: review.transaction_type ?? null,
    text: review.review ?? "",
  };
}

export function renderModule(result) {
  const { ownReviewsInFeed, ...data } = result;
  void ownReviewsInFeed;
  return `// Generated by scripts/experience-sync.mjs. Do not edit by hand.
// Aggregate figures only: no borrower names, emails, or review text.
export type ExperienceFigure = { rating: number; count: number };

export const experience: {
  checked: string;
  company: ExperienceFigure;
  blended: ExperienceFigure;
  officers: Record<string, ExperienceFigure>;
} = ${JSON.stringify(data, null, 2)};
`;
}

async function fetchPage(apiKey, widgetKey, page) {
  const url = new URL(FEED_URL);
  url.searchParams.set("widget_key", widgetKey);
  url.searchParams.set("api_key", apiKey);
  url.searchParams.set("status", "0,1");
  url.searchParams.set("is_abusive", "false");
  url.searchParams.set("is_duplicate", "false");
  url.searchParams.set("field", "survey_completed_on");
  url.searchParams.set("order", "desc");
  url.searchParams.set("limit", String(PAGE_SIZE));
  url.searchParams.set("page", String(page));
  const res = await fetch(url, { headers: { accept: "application/json" } });
  // The URL carries the key; never print it.
  if (!res.ok) throw new Error(`Experience.com feed returned HTTP ${res.status}`);
  const body = await res.json();
  if (!body?.survey_reviews) throw new Error("Experience.com feed had no survey_reviews");
  return body.survey_reviews;
}

export async function fetchAll(apiKey, widgetKey) {
  const first = await fetchPage(apiKey, widgetKey, 1);
  const reviews = [...first.reviews];
  const pages = Math.ceil(Number(first.count) / PAGE_SIZE);
  for (let page = 2; page <= pages; page++) {
    reviews.push(...(await fetchPage(apiKey, widgetKey, page)).reviews);
  }
  return { summary: first, reviews };
}

async function main() {
  const apiKey = process.env.EXPERIENCE_API_KEY;
  const widgetKey = process.env.EXPERIENCE_WIDGET_KEY;
  if (!apiKey || !widgetKey) {
    console.error("Set EXPERIENCE_API_KEY and EXPERIENCE_WIDGET_KEY.");
    process.exit(1);
  }
  const dryRun = process.argv.includes("--dry-run");
  const { summary, reviews } = await fetchAll(apiKey, widgetKey);
  const checked = new Date().toLocaleDateString("en-CA", {
    timeZone: "America/Los_Angeles",
  });
  const result = summarize(summary, reviews, checked);
  const problems = validate(result);
  if (problems.length) {
    console.error(`Refusing to write:\n- ${problems.join("\n- ")}`);
    process.exit(1);
  }
  console.log(
    `Experience.com own reviews: ${result.company.rating} from ${result.company.count}; ` +
      `blended ${result.blended.rating} from ${result.blended.count}; ` +
      `${Object.keys(result.officers).length} loan officers.`,
  );
  const candidatesAt = process.argv.indexOf("--candidates");
  if (candidatesAt > -1) {
    // Review candidates for a person to approve. Written outside the repo only:
    // this repository is public and unapproved quotes must not be committed.
    const path = process.argv[candidatesAt + 1];
    const since = process.argv[candidatesAt + 2] ?? "1970-01-01";
    if (!path) throw new Error("--candidates needs an output path");
    const candidates = reviews
      .filter((r) => isOwnReview(r) && Number(r.score) === 5)
      .filter((r) => String(r.review ?? "").trim().length >= 80)
      .filter((r) => String(r.survey_completed_on ?? "") >= since)
      .map(sanitizeReview);
    writeFileSync(path, JSON.stringify(candidates, null, 2));
    console.log(`Wrote ${candidates.length} review candidates to ${path}`);
  }
  if (dryRun) return;
  const out = fileURLToPath(new URL("../src/data/experience.generated.ts", import.meta.url));
  writeFileSync(out, renderModule(result));
  console.log(`Wrote ${out}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => {
    console.error(err.message);
    process.exit(1);
  });
}
